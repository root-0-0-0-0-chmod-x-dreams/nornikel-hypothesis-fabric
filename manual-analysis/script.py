import pandas as pd
import numpy as np

def generate_universal_brainstorm_report(file_path, metal_1_name="Никель (Эл 28)", metal_2_name="Медь (Эл 29)"):
    """
    Универсальный генератор отчетов для мозгового штурма на основе анализа хвостов обогащения.
    Supports: Минералогический, Грансоставный и Технологический срезы потерь.
    """
    try:
        df = pd.read_csv(file_path)
    except Exception as e:
        return f"Ошибка чтения файла: {e}. Убедитесь, что файл сохранен в кодировке UTF-8 и соответствует шаблону."
    
    # Проверка обязательных колонок
    required_cols = ['Анализ', 'Статья_Потерь', 'Металл_1_т', 'Металл_2_т']
    if not all(col in df.columns for col in required_cols):
        return f"Ошибка: Таблица должна содержать колонки: {required_cols}"
    
    # Очистка строк от пробелов
    df['Анализ'] = df['Анализ'].astype(str).str.strip()
    df['Статья_Потерь'] = df['Статья_Потерь'].astype(str).str.strip()
    
    report = []
    report.append("# МАТЕРИАЛЫ К ПРОВЕДЕНИЮ МОЗГОВОГО ШТУРМА: ОПТИМИЗАЦИЯ ПОКАЗАТЕЛЕЙ ОБРАБОТКИ ХВОСТОВ")
    report.append("=================================================================================")
    
    # 1. МИНЕРАЛОГИЧЕСКИЙ АНАЛИЗ ПОТЕРЬ
    min_df = df[df['Анализ'].str.lower() == 'минералогия'].copy()
    if not min_df.empty:
        total_m1_min = min_df['Металл_1_т'].sum()
        total_m2_min = min_df['Металл_2_т'].sum()
        
        report.append(f"\n## 1. Минералогический профиль потерь")
        report.append(f"• Всего идентифицировано потерь по минералам: {metal_1_name} = {total_m1_min:.2f} т, {metal_2_name} = {total_m2_min:.2f} т\n")
        
        hypotheses_grinding = []
        hypotheses_mag = []
        
        for _, row in min_df.iterrows():
            name = row['Статья_Потерь'].lower()
            m1_val = row['Металл_1_т']
            
            # Логика для силикатных форм и валлериита (Проблема раскрытия / Сростки)
            if any(x in name for x in ['силикат', 'валлериит', 'порода']):
                share = (m1_val / total_m1_min) * 100 if total_m1_min > 0 else 0
                if share > 20:
                    hypotheses_grinding.extend([
                        "   - Изменение геометрии футеровки шаровых мельниц для изменения характера внутримельничной среды (удар/истирание).",
                        "   - Переход на износостойкие мелящие шары повышенного класса (например, 5 класс) для стабилизации гранулометрического контура помола.",
                        "   - Оптимизация диаметра загружаемых шаров (например, 100% переход на диаметр 120 мм или комбинацию 90/120 мм) для разрушения прочных силикатных матриц."
                    ])
            
            # Логика для пирротина (Магнитные минералы)
            if any(x in name for x in ['пирротин', 'магнитн']):
                share = (m1_val / total_m1_min) * 100 if total_m1_min > 0 else 0
                if share > 10:
                    hypotheses_mag.extend([
                        "   - Внедрение стадиальной магнитной сепарации над целевого класса хвостов с выделением пирротинового продукта.",
                        "   - Направление выделенного пирротинового концентрата в отдельный замкнутый цикл доизмельчения (регриндинг) для вскрытия тонких включений цветных металлов без переизмельчения пустой породы.",
                        "   - Применение грохотов тонкого грохочения после II стадии измельчения как альтернативы/дополнения к магнитной сепарации."
                    ])
        
        if hypotheses_grinding:
            report.append("### Блок гипотез по рудоподготовке и раскрытию сульфидов:")
            report.extend(list(set(hypotheses_grinding)))
        if hypotheses_mag:
            report.append("\n### Блок гипотез по выделению магнитных фаз:")
            report.extend(list(set(hypotheses_mag)))

    # 2. ГРАНУЛОМЕТРИЧЕСКИЙ АНАЛИЗ (ШЛАМЫ vs КРУПНЫЕ СРОСТКИ)
    frac_df = df[df['Анализ'].str.lower() == 'фракции'].copy()
    if not frac_df.empty:
        report.append(f"\n## 2. Текстурно-гранулометрический профиль потерь")
        
        hypotheses_class = []
        hypotheses_flot = []
        hypotheses_crush = []
        
        for _, row in frac_df.iterrows():
            name = row['Статья_Потерь'].lower()
            m1_val = row['Металл_1_т']
            m2_val = row['Металл_2_т']
            
            # Анализ крупных классов и недоизмельчения (+74 мкм, сростки)
            if any(x in name for x in ['крупн', 'недоизмельч', 'сростк', '+74']):
                hypotheses_class.extend([
                    "   - Замена песковых насадок на гидроциклонах стадий классификации с уменьшением диаметра (например, с 12 на 8 или с 14 на 10) для увеличения циркулирующей нагрузки и возврата сростков на доизмельчение.",
                    "   - Модернизация узла классификации: переход от спиральных классификаторов к высокоэффективным гидроциклонам для повышения четкости разделения.",
                    "   - Замена насадок классификаторов для оперативного контроля плотности песков."
                ])
                hypotheses_crush.extend([
                    "   - Внедрение автоматического регулирования зазора щели конусных дробилок для стабилизации крупности питания мельниц.",
                    "   - Внедрение промежуточной дробилки рудной гали для снижения паразитной возвратной нагрузки на мельницы самоизмельчения / полуавтогенного измельчения.",
                    "   - Жесткий оперативный контроль гранулометрии руды после стадии мелкого дробления."
                ])
            
            # Анализ переизмельчения и шламов (-10 мкм, раскрытые металлы в хвостах)
            if any(x in name for x in ['шлам', 'мелк', '-10', 'раскрытый']):
                hypotheses_flot.extend([
                    "   - Повышение целевой плотности пульпы на входе в контур основной флотации для увеличения времени пребывания материала и снижения скорости потока шламистых частиц.",
                    "   - Организация дополнительных промежуточных контактных чанов для увеличения времени агитации с реагентами перед операциями контрольной флотации.",
                    "   - Внедрение специализированных модификаторов/депрессоров шламовых фракций и силикатов магния (например, карбоксиметилцеллюлоза или Finfix 300) в голову процесса.",
                    "   - Перераспределение фронта флотационных машин (изменение точек съема промпродуктов) для технологического удлинения времени первой и второй контрольных флотаций.",
                    "   - Автоматизация контуров подачи воды в шаровые мельницы для исключения гидравлического выноса некондиционных классов и минимизации шламообразования."
                ])
                
        if hypotheses_class or hypotheses_crush:
            report.append("### Блок гипотез по классификации и пред-дроблению:")
            report.extend(list(set(hypotheses_class + hypotheses_crush)))
        if hypotheses_flot:
            report.append("\n### Блок гипотез по флотационному контуру и реагентике:")
            report.extend(list(set(hypotheses_flot)))

    # 3. ЗАКЛЮЧИТЕЛЬНЫЕ РЕКОМЕНДАЦИИ ПО РАНЖИРОВАНИЮ (CAPEX/OPEX)
    report.append("\n## 3. Рекомендации по экспресс-фильтрации гипотез")
    report.append("1. **Quick Wins (Быстрые победы, минимальный CAPEX):** Оптимизация насадок гидроциклонов, автоматизация подачи воды, коррекция плотности флотации, промышленные испытания реагента Finfix 300.")
    report.append("2. **Среднесрочные проекты (Внутрицеховая модернизация):** Изменение футеровок мельниц при плановом перефутеровании, оптимизация шаровой загрузки, изменение схемных решений съема пены.")
    report.append("3. **Стратегические проекты (Высокий CAPEX):** Установка узлов тонкого грохочения, монтаж магнитных сепараторов, внедрение узлов дробления гали.")
    
    return "\n".join(report)

